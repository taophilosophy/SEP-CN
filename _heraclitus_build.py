def load_src():
    with open(SRC, encoding='utf-8') as fh:
        return fh.read().splitlines()

def seg_source(lines, ids):
    """按行区间抽取源文本（保留空行，去除区间外尾随空行）。"""
    src = []
    for sid in ids:
        for n in SEG_RANGES[sid]:
            src.append(lines[n - 1])
    # 去除首尾空行
    while src and not src[0].strip():
        src.pop(0)
    while src and not src[-1].strip():
        src.pop()
    return "\n".join(src)

def yaml_block(text, indent):
    """生成 |- 块标量内容行（已 indentation 缩进），返回行列表。"""
    if text is None:
        text = ""
    pad = " " * indent
    out = []
    lines = text.split("\n")
    for ln in lines:
        out.append(pad + ln if ln else "")
    return out

def render_ledger(tr):
    lines = []
    lines.append("version: 1")
    lines.append("slug: heraclitus")
    lines.append("segments:")
    for sid in sorted(tr):
        s1, s2 = tr[sid]
        lines.append("  - id: %d" % sid)
        lines.append("    source: |-")
        lines.extend(yaml_block(seg_source(load_src(), [sid]), 6))
        lines.append("    step1: |-")
        lines.extend(yaml_block(s1, 6))
        lines.append("    step2: |-")
        lines.extend(yaml_block(s2, 6))
    return "\n".join(lines) + "\n"

