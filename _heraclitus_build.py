def render_doc(tr):
    lines = []
    lines.append("# 赫拉克利特 Heraclitus (Daniel W. Graham)")
    lines.append("")
    lines.append("*首次发表于 2007 年 2 月 8 日；2023 年 12 月 8 日实质修订。*")
    lines.append("")
    for sid in sorted(tr):
        if sid in HEADINGS_AT:
            lines.append(HEADINGS_AT[sid])
            lines.append("")
        lines.append(tr[sid][1])
        lines.append("")
    return "\n".join(lines)

