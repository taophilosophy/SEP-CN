def main():
    rows = list(csv.DictReader(open(TSV, encoding='utf-8'), delimiter='\t'))
    for r in rows:
        slug = r['slug']
        parts = r['new_section'].split(' > ')
        if slug in HEAD:
            r['sort_key'] = '-9999'
            r['confidence'] = 'C'
        elif slug in BIRTH:
            r['sort_key'] = str(BIRTH[slug])
            r['confidence'] = 'A'
        elif len(parts) > 1 and parts[0] == '西方哲学史':
            r['sort_key'] = str(DEFAULT.get(parts[1], 0))
            r['confidence'] = 'C'
        else:
            r['sort_key'] = '0'
            r['confidence'] = ''
        r['note'] = NOTE.get(slug, '')
    with open(TSV, 'w', encoding='utf-8', newline='') as f:
        w = csv.DictWriter(f, fieldnames=['slug', 'title', 'current_section', 'new_section', 'parent', 'sort_key', 'confidence', 'note'], delimiter='\t')
        w.writeheader()
        w.writerows(rows)
    print('rows', len(rows), 'with birth', sum(1 for r in rows if r['confidence'] == 'A'))


if __name__ == '__main__':
    main()
